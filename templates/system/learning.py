def snapshot_age_note(started_at: str, *, stale_days: int = 14) -> str:
    """Flag an index snapshot that is old enough to mislead; never blocks brief."""
    try:
        taken = datetime.fromisoformat(started_at)
    except (TypeError, ValueError):
        return ''
    now = datetime.now(taken.tzinfo or timezone.utc)
    days = (now - taken).days
    if days < stale_days:
        return ''
    return f'（已过期 {days} 天，重建：python3 数据层/统一索引/脚本/sync_learning_os.py）'

def tree_lines(items: list[Path]) -> list[str]:
    registered = {subject.relative_to(SUBJECTS): subject for subject in items}
    visible = set()
    for relative in registered:
        visible.update(Path(*relative.parts[:index]) for index in range(1, len(relative.parts) + 1))
    lines = []
    for relative in sorted(visible, key=lambda p: tuple(p.parts)):
        depth = len(relative.parts) - 1
        subject = registered.get(relative)
        label = node_role(subject, items) if subject else "category"
        lines.append(f"{'  ' * depth}- {relative.name} [{label}]")
    return lines

def nearest_registered_parent(subject: Path, items: list[Path]) -> Path | None:
    parents = [candidate for candidate in items if candidate != subject and candidate in subject.parents]
    return max(parents, key=lambda item: len(item.parts)) if parents else None

def metadata_value(text: str, key: str) -> str | None:
    match = re.search(rf"^{re.escape(key)}:\s*(.+?)\s*$", text, re.M)
    return match.group(1).strip().strip('"\'') if match else None

def frontmatter_block(text: str) -> str:
    """Return only the YAML frontmatter (between the leading and next '---' lines).

    Files without a leading '---' frontmatter block return ''. This keeps
    metadata_value from matching example `key: value` lines that merely
    appear in a file's body (e.g. a template showing what frontmatter looks
    like), which are not real evidence metadata.
    """
    if not text.startswith('---\n'):
        return ''
    end = text.find('\n---', 4)
    return text[:end] if end != -1 else ''

def evidence_records(subject: Path, recursive: bool = False) -> list[dict]:
    roots = [subject / '学习记录', subject / '练习']
    if recursive:
        roots = []
        for child in subjects():
            if child == subject or subject in child.parents:
                roots.extend([child / '学习记录', child / '练习'])
    records = []
    for root in roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob('*.md')):
            if path.is_symlink() or not path.resolve().is_relative_to(ROOT):
                continue
            if path.name == 'README.md' or '自动续学' in path.parts:
                continue
            try:
                text = path.read_text(encoding='utf-8')
            except (OSError, UnicodeError):
                continue
            front = frontmatter_block(text)
            kind = metadata_value(front, 'kind')
            if kind not in EVIDENCE_KINDS:
                continue
            records.append({
                'kind': kind,
                'subject': metadata_value(front, 'subject') or subject_label(subject),
                'module': metadata_value(front, 'module') or '未标注模块',
                'occurred_at': metadata_value(front, 'occurred_at') or '时间未标注',
                'result': metadata_value(front, 'result') or '未标注结果',
                'path': path,
            })
    return records


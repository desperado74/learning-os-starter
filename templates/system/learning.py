def atomic_write(path: Path, text: str) -> None:
    if not path.resolve().is_relative_to(ROOT):
        raise ValueError('Write target escapes this private workspace.')
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temp = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp, path)
    finally:
        if temp.exists():
            temp.unlink()

def subjects() -> list[Path]:
    result = []
    for current, dirs, files in os.walk(SUBJECTS):
        dirs[:] = [d for d in dirs if not (Path(current)/d).is_symlink() and d not in {'资料', '模块', '学习记录', '练习', 'Anki', '总管归档', '.git', '__pycache__'}]
        if '学习主页.md' in files and 'AGENTS.md' in files and not any((Path(current)/f).is_symlink() for f in ('学习主页.md','AGENTS.md')):
            result.append(Path(current))
    return sorted(result)

def subject_label(subject: Path) -> str:
    return str(subject.relative_to(SUBJECTS))

def page(subject: Path) -> str:
    return (subject / "学习主页.md").read_text(encoding="utf-8")

def leaf_subject_for_cwd(cwd: str | None = None) -> Path | None:
    current = Path(cwd or os.getcwd()).resolve()
    try:
        current.relative_to(SUBJECTS.resolve())
    except ValueError:
        return None
    for candidate in [current, *current.parents]:
        if (candidate / 'AGENTS.md').exists() and (candidate / '学习主页.md').exists():
            return candidate if node_type(page(candidate)) == 'leaf' else None
        if candidate == SUBJECTS.resolve():
            break
    return None

def continuation_files(subject: Path) -> list[Path]:
    """Only curated bookmarks; automatic excerpt experiment is paused."""
    position = subject / '续学位置.md'
    return [position] if position.exists() else []

def position_text(subject: Path) -> str:
    sources = continuation_files(subject)
    if any(p.name == '自动续学片段.md' for p in sources):
        return '有自动对话片段，学习位置待核对（不等于已掌握）'
    position = subject / "续学位置.md"
    if not position.exists():
        return "未同步"
    text = position.read_text(encoding="utf-8").strip()
    closed = bool(re.search(r'^phase: closed\s*$', text, re.M))
    text = re.sub(r'\A---\s*\n.*?\n---\s*\n', '', text, flags=re.S)
    text = '\n'.join(line for line in text.splitlines() if not line.startswith(('#', '保存时间：', '当前模块：')))
    return ('已收尾｜' if closed else '') + first_nonempty_line(text) if text.strip() else "未同步"

def first_nonempty_line(text: str) -> str:
    return next((line.strip("- ") for line in text.splitlines() if line.strip()), "未同步")

def clip(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"

def node_type(text: str) -> str | None:
    match = re.search(r"^node_type:\s*(manager|leaf)\s*$", text, re.M)
    return match.group(1) if match else None

def node_role(subject: Path, all_subjects: list[Path] | None = None) -> str:
    explicit = node_type(page(subject))
    if explicit in NODE_TYPES:
        return explicit
    candidates = all_subjects if all_subjects is not None else subjects()
    prefix = subject.relative_to(SUBJECTS)
    if any(other != subject and prefix in other.relative_to(SUBJECTS).parents for other in candidates):
        return "manager"
    return "leaf"

def relative_subject(path_text: str) -> Path | None:
    candidate = (SUBJECTS / path_text).resolve()
    try:
        candidate.relative_to(SUBJECTS.resolve())
    except ValueError:
        return None
    return candidate

def section(text: str, heading: str) -> str:
    match = re.search(
        rf"^## {re.escape(heading)}(?:（[^）]*）|\([^)]*\))?\s*$\n(.*?)(?=^##\s|\Z)",
        text,
        re.M | re.S,
    )
    return match.group(1).strip() if match else ""

def first_line(text: str, heading: str) -> str:
    return next((line.strip().lstrip("- ") for line in section(text, heading).splitlines() if line.strip()), "暂无")

def score(query: str, candidate: str) -> float:
    norm = lambda value: "".join(char for char in value.casefold() if char.isalnum())
    q, c = norm(query), norm(candidate)
    if q == c:
        return 1.0
    if q in c or c in q:
        return 0.9
    return difflib.SequenceMatcher(None, q, c).ratio()

def aliases(text: str) -> list[str]:
    match = re.search(r"^aliases:\s*\[(.*?)\]\s*$", text, re.M)
    if not match:
        return []
    return [item.strip().strip('"\'') for item in match.group(1).split(",") if item.strip()]

def broken_local_links(path: Path) -> list[str]:
    """Check ordinary Markdown links while ignoring URLs and page anchors."""
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        return []
    broken = []
    for match in re.finditer(r'\[[^\]]*\]\((<[^>]+>|[^)]+)\)', text):
        raw = match.group(1).strip()
        target = raw[1:-1] if raw.startswith('<') and raw.endswith('>') else raw.split()[0]
        target = target.split('#', 1)[0]
        if not target or re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', target):
            continue
        resolved = Path(target) if target.startswith('/') else path.parent / target
        if not resolved.exists():
            broken.append(raw)
    return broken

def heading_slugs(path: Path) -> set[str]:
    """GitHub 风格的标题锚点：去标点、空格转连字符；重复标题不追加序号（本库标题不重复）。"""
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        return set()
    slugs = set()
    in_code = False
    for line in text.splitlines():
        if line.startswith('```'):
            in_code = not in_code
        match = re.match(r'^#{1,6}\s+(.*?)\s*#*\s*$', line)
        if match and not in_code:
            title = re.sub(r'[`*_]', '', match.group(1)).strip().lower()
            slugs.add(re.sub(r'\s+', '-', re.sub(r'[^\w\- ]', '', title, flags=re.UNICODE)))
    return slugs

def broken_anchors(path: Path, only_targets: set[Path] | None = None) -> list[str]:
    """检查指向 Markdown 文件的 #锚点是否对应真实标题；only_targets 限定被检查的目标文件。"""
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        return []
    broken = []
    for match in re.finditer(r'\[[^\]]*\]\((<[^>]+>|[^)]+)\)', text):
        raw = match.group(1).strip()
        target = raw[1:-1] if raw.startswith('<') and raw.endswith('>') else raw.split()[0]
        if '#' not in target or re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', target):
            continue
        file_part, anchor = target.split('#', 1)
        resolved = path if not file_part else (Path(file_part) if file_part.startswith('/') else path.parent / file_part)
        if not resolved.resolve().is_relative_to(ROOT) or not resolved.is_file() or resolved.suffix != '.md' or not anchor:
            continue
        if only_targets is not None and resolved.resolve() not in only_targets:
            continue
        if anchor.lower() not in heading_slugs(resolved):
            broken.append(raw)
    return broken

def resolve_candidates(query: str, *, threshold: float = 0.72) -> list[Path]:
    """Best-scoring nodes for a query, with ancestors of a tied descendant dropped.

    A manager that lists its own child as an alias scores exactly as high as that
    child (数学一 aliases 概率论). The child is the real learning entry, so an
    ancestor never wins a tie against its own descendant. Unrelated ties such as
    408/数据结构 vs 804/数据结构 stay ambiguous for the caller to report.
    """
    registered = subjects()
    exact = relative_subject(query)
    if exact in registered:
        return [exact]
    ranked = sorted(
        ((max(score(query, label) for label in [subject.name, subject_label(subject), *aliases(page(subject))]), subject)
         for subject in registered),
        key=lambda item: (-item[0], item[1].name),
    )
    if not ranked or ranked[0][0] < threshold:
        return []
    tied = [subject for value, subject in ranked if value == ranked[0][0]]
    return [s for s in tied if not any(other is not s and s in other.parents for other in tied)]

def resolve(query: str) -> Path | None:
    candidates = resolve_candidates(query)
    return candidates[0] if len(candidates) == 1 else None


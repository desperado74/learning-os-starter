    paths += [subject / name for name in ('长期路线.md', '长期学习路线.md')]
    paths += continuation_files(subject)
    total = 0
    for path in paths:
        if not path.exists(): continue
        value = path.read_text(encoding='utf-8')
        limit = min(3500, max(0, 10000-total))
        print(f'\n## {path}\n{value[:limit]}')
        if len(value) > limit: print(f'【资料摘要已截断；执行前须完整读取相关文件：{path}】')
        total += min(len(value), limit)
    print('\n接下来按主页定位当前模块、原题清单和最近交接，核准内容与题目两部分；partial交接先接剩余任务，不按文件名最大值推断已完成。本命令未读取原题或确认完成，相关模块、清单和原题区仍须读取。')
    return 0

